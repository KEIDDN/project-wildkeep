import type { ToolKind } from "./items";

export type GatherAnim = "chop" | "mine" | "collect" | "water";
export type ParticleKind = "wood" | "leaf" | "stone" | "ore" | "coal" | "gold" | "crystal" | "herb";

export interface ResourceNodeDef {
  id: string;
  name: string;
  sprite: string; // prop sprite id
  depletedSprite?: string; // prop shown while regrowing (stump, rubble, sprout)
  toolKind?: ToolKind; // undefined = by hand
  toolPowerRequired: number;
  hits: number; // tool power is subtracted per swing
  anim: GatherAnim;
  particles: ParticleKind[];
  respawnSec: number;
  xp: number;
  skill: "woodcutting" | "mining" | "gathering";
  /** `rare` drops get more likely with the node's skill level and Luck. */
  drops: { itemId: string; min: number; max: number; chance?: number; rare?: boolean }[];
  /** Feet collider for the node while standing (relative to its base). */
  collider?: { w: number; h: number };
  /** Sprite tweaks so one prop can stand in for a bigger / stranger node. */
  scale?: number;
  tint?: number;
  /** Soft glow (crystals, moonpetals). */
  glow?: number;
  /** Only harvestable at night (see game/time/clock isNight). */
  nightOnly?: boolean;
}

